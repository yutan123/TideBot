      '10-31': '节日:万圣节',
      '12-24': '节日:平安夜',
      '12-25': '节日:圣诞节',
    };
    final observance = observances['${date.month}-${date.day}'];
    if (observance != null) labels.add(observance);
    return labels;
  }

