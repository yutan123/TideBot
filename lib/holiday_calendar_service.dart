  static String contextFor(DateTime now) {
    final days = <String>[];
    for (var offset = -1; offset <= 1; offset++) {
      final date = DateTime(now.year, now.month, now.day + offset);
      final labels = _labels(date);
      days.add(
        '${_date(date)} ${_weekday(date)}${labels.isEmpty ? '' : ' ${labels.join('、')}'}',
      );
    }
    return '现实日期上下文（内部元数据，不得复述格式）：${days.join('；')}。时区为设备本地时区。';
  }

  static List<String> _labels(DateTime date) {
    final key = _date(date);
    final labels = <String>[];
    final annual = _annualCalendar[key];
